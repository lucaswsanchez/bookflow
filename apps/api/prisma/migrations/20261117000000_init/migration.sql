-- Prevent overlapping active appointments for the same staff member at the database level.
-- btree_gist lets a GiST index combine equality on "staffId" with range overlap on time.
-- The extension lives in an "extensions" schema (Supabase convention) and the operator
-- class is schema-qualified so it works regardless of the connection's search_path.
CREATE SCHEMA IF NOT EXISTS extensions;
CREATE EXTENSION IF NOT EXISTS btree_gist WITH SCHEMA extensions;

ALTER TABLE "Appointment"
  ADD CONSTRAINT "Appointment_no_overlap"
  EXCLUDE USING gist (
    "staffId" extensions.gist_text_ops WITH =,
    tstzrange("startsAt", "endsAt", '[)') WITH &&
  ) WHERE (status <> 'CANCELLED');

ALTER TABLE "Appointment"
  ADD CONSTRAINT "Appointment_valid_range" CHECK ("endsAt" > "startsAt");
